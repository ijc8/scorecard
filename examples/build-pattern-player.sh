#!/bin/sh
# Builds the player for the source face's Pattern mode (pattern-player.c) into the app, as
# src/patternPlayer.ts.
cd "$(dirname "$0")" && ./build.sh pattern-player.c && {
    echo "// Generated by examples/build-pattern-player.sh from examples/pattern-player.c."
    echo "export default \"$(base64 -w0 pattern-player.wasm)\""
} > ../src/patternPlayer.ts
