const { chromium } = require('playwright');
(async () => {
  const S = process.argv[2]
  const lib = require(require('path').join(__dirname, '../../src/library.json'))
  const browser = await chromium.launch()
  const page = await browser.newPage({ viewport: { width: 375, height: 720 } })
  page.on("pageerror", e => console.log("ERR", e.message))
  page.on("dialog", d => d.accept())
  const count = () => page.evaluate(() => [JSON.parse(localStorage["scorecard-deck"] || "[]").length, JSON.parse(localStorage["scorecard-packs"] || "null")?.length])
  await page.goto("http://localhost:4173/?c=" + encodeURIComponent(lib[1].code)); await page.waitForTimeout(500)
  await page.click(".tabs button[title='Settings']"); await page.waitForTimeout(300)
  await page.screenshot({ path: `${S}/settings.png` })
  console.log("start [deck, packs]:", await count(), "starter btn disabled:", await page.locator("text=Get a fresh starter pack").isDisabled())
  await page.click("text=Empty my deck"); console.log("emptied:", await count())
  await page.click("text=Collect cards"); await page.click("text=Animations")
  await page.goto("http://localhost:4173/?c=" + encodeURIComponent(lib[2].code)); await page.waitForTimeout(500)
  console.log("collect off, followed link:", await count(), "still class:", await page.evaluate(() => document.documentElement.className))
  await page.click(".deck-handle"); await page.waitForTimeout(100); await page.click(".pack"); await page.waitForTimeout(200)
  console.log("opened pack (no motion):", await count())
  await page.click(".deck-close"); await page.click(".tabs button[title='Settings']")
  await page.click("text=Get a fresh starter pack"); await page.waitForTimeout(200); console.log("fresh starter:", await count())
  const wide = await browser.newPage({ viewport: { width: 1000, height: 860 } })
  await wide.goto("http://localhost:4173/?c=" + encodeURIComponent(lib[1].code)); await wide.waitForTimeout(900)
  await wide.locator(".tabs").screenshot({ path: `${S}/tabs-wide.png` })
  await browser.close()
})()
